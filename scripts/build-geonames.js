'use strict';
// One-off generator for src/data/geonames.js from a GeoNames cities dump (tab-separated).
// Not run automatically at server start — the output is a plain checked-in data file, same
// spirit as src/data/places.js (no live dependency on GeoNames at runtime).
//
// Usage: node scripts/build-geonames.js scripts/data-src/cities15000.txt > src/data/geonames.js
// Source: https://download.geonames.org/export/dump/cities15000.zip (CC BY 4.0, geonames.org)

const fs = require('fs');

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/build-geonames.js <cities-dump.txt>');
  process.exit(1);
}

const MIN_NAME_LEN = 4;
// Confirmed false positives, added as found (not a guess at every possible collision — see
// src/lib/geo.js for the systemic fixes: population tie-break, curated-wins-ties, country-name
// protection). "Central" matched "Brazil central bank holds interest rates steady" via the small
// US town Central, LA — an ordinary English word, no population size fixes that.
const BLOCKLIST = new Set(['central']);
// Only the two authoritative GeoNames name fields (name, asciiname) are used — no shortened/derived
// aliases. Tried two heuristics, both leaked false positives: GeoNames' crowdsourced "alternatenames"
// field includes phonetic transliterations that coincide with ordinary words ("casa" — Portuguese
// for "house" — transliterates the Indian town "Chas"; "Boseman" transliterates "Bozeman", Montana,
// colliding with actor Chadwick Boseman's surname); and splitting compound names on the first
// separator ("Cluj-Napoca" -> "Cluj") also fires on genuine two-word names ("Casa Verde" -> "Casa").
// A handful of well-known short forms (e.g. "Cluj") are added by hand in src/data/places.js instead.
//
// Population floor is 50,000, not the input file's own 15,000 (cities15000.txt) — raised after
// finding real false positives in ordinary English text at the lower cutoff ("central bank" matching
// the 28k-person US town Central; "bank" matching the 18k-person Indian town Bank). An ordinary
// word coinciding with a real place name is far more likely among obscure small towns than among
// genuinely notable cities, so this trades away long-tail coverage for reliability — still ~12,000
// cities worldwide, everywhere anyone would plausibly write news about.
const MIN_POPULATION = 50000;

const lines = fs.readFileSync(file, 'utf8').split('\n');
const parsed = [];

for (const line of lines) {
  if (!line.trim()) continue;
  const c = line.split('\t');
  const name = c[1];
  const asciiname = c[2];
  if ((Number(c[14]) || 0) < MIN_POPULATION) continue;
  const lat = Number(c[4]);
  const lon = Number(c[5]);
  const iso = c[8];
  const population = Number(c[14]) || 0;
  if (!name || !iso || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;

  const core = [name];
  if (asciiname && asciiname.toLowerCase() !== name.toLowerCase()) core.push(asciiname);

  const candidates = core.filter((n) =>
    n.replace(/[^\p{L}\p{N}]/gu, '').length >= MIN_NAME_LEN && !BLOCKLIST.has(n.toLowerCase())
  );
  if (!candidates.length) continue;

  parsed.push({ candidates, lat, lon, iso, population });
}

// Two identically-named places (e.g. "Naples" IT vs "Naples" US-FL) can't both own that exact
// term in a flat name -> coords lookup. Resolve by population: only the most populous owner of a
// given name string keeps it. A smaller place can lose ALL its candidate names this way (falls
// back to its country centroid at query time — acceptable; better than randomly picking one).
const bestPop = new Map(); // nameLower -> highest population seen for that exact string
for (const p of parsed) {
  for (const n of p.candidates) {
    const key = n.toLowerCase();
    if (!bestPop.has(key) || p.population > bestPop.get(key)) bestPop.set(key, p.population);
  }
}

const seen = new Set(); // dedup by "lowercased-first-name|iso"
const rows = [];
for (const p of parsed) {
  const names = p.candidates.filter((n) => bestPop.get(n.toLowerCase()) === p.population);
  if (!names.length) continue;
  const key = `${names[0].toLowerCase()}|${p.iso}`;
  if (seen.has(key)) continue;
  seen.add(key);
  rows.push([names.join('|'), Number(p.lat.toFixed(4)), Number(p.lon.toFixed(4)), p.iso, p.population]);
}

rows.sort((a, b) => a[0].localeCompare(b[0]));

const header = `'use strict';
// Auto-generated by scripts/build-geonames.js from GeoNames cities15000.txt (population >= 15000).
// Source: https://www.geonames.org/ (CC BY 4.0) — see https://download.geonames.org/export/dump/.
// Regenerate: node scripts/build-geonames.js scripts/data-src/cities15000.txt > src/data/geonames.js
// Format extends src/data/places.js PLACES with a 5th field: [names|joined|by|pipe, lat, lon, iso2, population].
// The population lets src/lib/geo.js prefer the more notable place when two different real places
// share a name (e.g. "Paris" FR vs "Paris" US-TX) — see resolveBestHit() there. Hand-picked entries
// in places.js have no 5th field (population 0), which keeps their original text-position tie-break
// intact — this base layer only affects ties among GeoNames-sourced entries.

module.exports = [
`;
const footer = '];\n';
const body = rows.map((r) => `  [${JSON.stringify(r[0])}, ${r[1]}, ${r[2]}, ${JSON.stringify(r[3])}, ${r[4]}],`).join('\n');

process.stdout.write(header + body + '\n' + footer);
console.error(`${rows.length} places written (from ${lines.length} input rows)`);
